def _output(code):
    """What the snippet prints: its stdout, «Қате» if it raises, «Бос жол» if it prints only an empty line."""
    buf = io.StringIO()
    try:
        with contextlib.redirect_stdout(buf):
            exec(code, {})
    except Exception:
        return 'Қате'
    return buf.getvalue().strip() or 'Бос жол'


def P(difficulty, code, opts):
    """'What does it print?' question: the code is executed and the correct option is the real output."""
    out = _output(code)
    if out not in opts:
        raise SystemExit(f'python: output {out!r} is not among the options of:\n{code}')
    return (difficulty, PRINTS + code, opts, opts.index(out), ('eq', out))


def C(difficulty, q, opts, correct, check=None):
    return (difficulty, q, opts, correct) + ((check,) if check else ())


